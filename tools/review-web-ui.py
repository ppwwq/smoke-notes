    m.get_by_role('button', name='重命名便签本', exact=True).click()
    rename = m.get_by_role('textbox', name='重命名：手机测试本')
    rename.fill('手机重命名'); rename.press('Enter')
    expect(m.get_by_role('button', name='手机重命名', exact=True)).to_be_visible()
