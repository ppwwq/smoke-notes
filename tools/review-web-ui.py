    page.get_by_role('button', name='全部', exact=True).click()
    page.get_by_role('textbox', name='新待办内容').fill('浏览器回归待办')
    page.get_by_role('button', name='添加', exact=True).click()
    task = page.get_by_role('textbox', name='编辑待办：浏览器回归待办')
    task.fill('浏览器回归待办，已修改')
