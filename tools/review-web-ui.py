    page.reload()
    expect(page.get_by_role('button', name='打开便签：离线修改保留')).to_be_visible()
    check('Offline edit persists through reconnect and reload')
    # Fresh sample context for consistent final mobile screenshots.
    mobile = browser.new_context(viewport={'width': 390, 'height': 844}, is_mobile=True, has_touch=True)
    m = mobile.new_page(); m.on('pageerror', lambda error: errors.append(str(error))); m.goto(BASE)
    expect(m.get_by_role('heading', name='日常灵感', exact=True)).to_be_visible()
    capture(m, 'mobile-notes')
    m.get_by_role('button', name='新建便签', exact=True).click()
    capture(m, 'mobile-create-menu')
    m.keyboard.press('Escape')
    expect(m.get_by_role('menu', name='便签类型')).to_have_count(0)
    nav(m, '浏览便签本')
    capture(m, 'mobile-notebooks-stacked')
    m.get_by_role('button', name='展开卡片', exact=True).click()
