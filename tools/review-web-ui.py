    m.get_by_role('button', name='进入便签本：日常灵感').click()
    check('Mobile create/rename/delete/restore notebook and drawer keyboard dismissal')
    nav(m, '待办'); capture(m, 'mobile-todos')
    m.get_by_role('button', name='完成：读二十页喜欢的书').click()
    m.get_by_role('button', name='完成：给家人打个电话').click()
    capture(m, 'mobile-todos-completed')
    nav(m, '便签')
    m.get_by_role('button', name='打开便签：今天慢慢做', exact=True).click()
    expect(m.locator('.tiptap')).to_be_visible()
    capture(m, 'mobile-editor-checklist')
    m.get_by_role('checkbox').first.click()
    m.get_by_role('button', name='保存', exact=True).click()
    expect(m.get_by_label('保存状态')).to_contain_text(re.compile('已(自动)?保存'))
    # A virtual landscape keyboard viewport must expose compact controls without losing the draft.
    m.get_by_role('textbox', name='便签标题', exact=True).fill('手机清单草稿')
    m.set_viewport_size({'width': 844, 'height': 600})
