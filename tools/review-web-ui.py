"""Browser acceptance and screenshots for the isolated review build.
Run after pnpm --filter @smoke-notes/web build:review and serving dist-review on 4173.
Requires Python Playwright + Chromium. Never points at production or reads user data.
"""
import json
import os
import re
from pathlib import Path
from playwright.sync_api import sync_playwright, expect

BASE = os.environ.get('SMOKE_REVIEW_URL', 'http://127.0.0.1:4173/review.html')
OUT = Path(os.environ.get('SMOKE_REVIEW_OUTPUT', '/workspace/shared/smoke-ui-review'))
OUT.mkdir(parents=True, exist_ok=True)
results = []

def check(name):
    results.append(name)

def capture(page, name):
    # Capture settled UI; do not confuse a viewport transition with its resting layout.
    page.wait_for_timeout(350)
    assert page.evaluate('document.documentElement.scrollWidth <= innerWidth'), name
    page.screenshot(path=str(OUT / (name + '.png')), clip={'x':0,'y':0,'width':844,'height':320}) if name == 'landscape-editor-format' else page.screenshot(path=str(OUT / (name + '.png')), full_page=True)

def nav(page, name):
    page.get_by_role('navigation', name='手机主导航').get_by_role('button', name=name, exact=True).click()

