    check('320/390/768/1024/1440 layouts without document overflow; reduced motion disables transitions')
    assert not errors, errors
    report = {'passed':results, 'pageErrors':errors, 'screenshots': sorted(f.name for f in OUT.glob('*.png')), 'url': BASE}
    (OUT / 'browser-results.json').write_text(json.dumps(report, ensure_ascii=False, indent=2))
    print(json.dumps(report, ensure_ascii=False))
